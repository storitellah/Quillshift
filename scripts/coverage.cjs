// Derives the set of code points covered by pdfmake's bundled Roboto and writes
// js/convert/roboto-coverage.js, so the app can tell when a document needs the
// snapshot renderer instead of the text renderer.
const fs = require('fs'); const path = require('path');
const fontkit = require('@foliojs-fork/fontkit');


// The package is "type": "module", so evaluate this classic script by hand.
const mod = { exports: {} };
new Function('module', fs.readFileSync(path.join(__dirname, '../vendor/vfs_fonts.js'), 'utf8'))(mod);
const vfs = mod.exports;
const font = fontkit.create(Buffer.from(vfs['Roboto-Regular.ttf'], 'base64'));
const cps = [...font.characterSet].filter((c) => c >= 0x20).sort((a, b) => a - b);
const ranges = [];
for (const c of cps) { const l = ranges[ranges.length - 1]; if (l && l[1] === c - 1) l[1] = c; else ranges.push([c, c]); }
const flat = ranges.flat();
fs.writeFileSync(path.join(__dirname, '../js/convert/roboto-coverage.js'),
`// Generated by scripts/coverage.cjs — code point ranges [start, end, start, end, …]\n// covered by the Roboto build that ships with pdfmake.\nexport const ROBOTO_RANGES = [${flat.join(',')}];\n`);
console.log(Object.keys(vfs), cps.length, 'code points', ranges.length, 'ranges');
const has = (ch) => font.characterSet.includes(ch.codePointAt(0));
