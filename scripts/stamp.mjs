// Writes precache-manifest.js: the list of app-shell files and a content hash.
// The service worker installs a fresh cache whenever the hash changes, so run
// `npm run stamp` after editing anything under css/, js/, icons/ or index.html.
// `--check` exits non-zero when the committed manifest is stale (used by tests and CI).
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => readdirSync(join(root, dir)).flatMap((n) => {
  const rel = `${dir}/${n}`;
  return statSync(join(root, rel)).isDirectory() ? walk(rel) : [rel];
});
const files = ['index.html', 'manifest.webmanifest', ...walk('css'), ...walk('js'), ...walk('icons').filter((f) => /\.(png|svg)$/.test(f))].sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);
const out = `// Generated by scripts/stamp.mjs — do not edit by hand.\nself.__QUILLSHIFT = ${JSON.stringify({ version, files: ['./', ...files] }, null, 2)};\n`;
const target = join(root, 'precache-manifest.js');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('precache-manifest.js is out of date. Run `npm run stamp`.');
    process.exit(1);
  }
  console.log(`precache-manifest.js is current (${version}).`);
} else {
  writeFileSync(target, out);
  console.log(`Stamped ${files.length} files as ${version}.`);
}
